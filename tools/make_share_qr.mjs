// Writes cards/config/share_qr.yaml, the QR matrix of the site address, so the game draws the code itself and asks no outside service.
// Needs the npm package qrcode, which is not part of the game: set QR_DIR to a folder where it is installed.
//   QR_DIR=path/to/folder node tools/make_share_qr.mjs
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const yaml = createRequire(import.meta.url)(path.join(root, 'vendor/js-yaml.min.js'));
const qrDir = process.env.QR_DIR;
if (!qrDir) { console.error('set QR_DIR to a folder with the qrcode package installed'); process.exit(1); }
const QR = createRequire(path.join(qrDir, 'x.js'))('qrcode');
const config = yaml.load(fs.readFileSync(path.join(root, 'cards/config/config.yaml'), 'utf8'));
const url = config.meta.links.site;
const code = QR.create(url, { errorCorrectionLevel: 'M' });
const n = code.modules.size;
const rows = [];
for (let y = 0; y < n; y++) {
  let r = '';
  for (let x = 0; x < n; x++) r += code.modules.get(x, y) ? '1' : '0';
  rows.push(r);
}
const out = '# Generated by tools/make_share_qr.mjs from meta.links.site. Run it again if the address changes.\n' + yaml.dump({ url, rows }, { lineWidth: -1 });
fs.writeFileSync(path.join(root, 'cards/config/share_qr.yaml'), out);
console.log(`QR ${n}x${n} for ${url}`);
