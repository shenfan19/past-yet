// Packs the cards folder into the data the game reads. Edit the cards, then run:
//   node tools/build_data.mjs           write data/
//   node tools/build_data.mjs --check   write nothing, exit 1 if data/ differs from what the cards would produce
// One card is one yaml file. A card holds the structure of a thing and its text in every language, so one thing is changed in one place.
// A historical person is a module: the folder cards/people/<person>/ holds everything about that person, the person card, the events, the model of an era, the wiki cards,
// the sources and the antiques, and a folder can be dropped in or taken out whole. See cards/README.md for the layout.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { checkStory, storyReport } from './story_rules.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const yaml = createRequire(import.meta.url)(path.join(root, 'vendor/js-yaml.min.js'));
const check = process.argv.includes('--check');
const CARDS = path.join(root, 'cards');
const OUT = path.join(root, 'data');
const HEADER = '# Generated by tools/build_data.mjs from the cards folder. Do not edit this file, edit the cards and run the build.\n';

const problems = [];
const fail = (msg) => problems.push(msg);
const isObj = (x) => x !== null && typeof x === 'object' && !Array.isArray(x);
const read = (rel) => yaml.load(fs.readFileSync(path.join(CARDS, rel), 'utf8'));
const exists = (rel) => fs.existsSync(path.join(CARDS, rel));
const yamlFiles = (dir) => (exists(dir) ? fs.readdirSync(path.join(CARDS, dir)).filter((f) => f.endsWith('.yaml')).sort() : []);
// objects merge key by key, anything else is replaced whole, the same rule the game uses for languages
function merge(base, over) {
  if (!isObj(base) || !isObj(over)) return over;
  const out = { ...base };
  for (const k of Object.keys(over)) out[k] = k in base ? merge(base[k], over[k]) : over[k];
  return out;
}

const config = read('config/config.yaml');
const LANGS = Object.keys(config.i18n.locales);
const defaultAuthors = config.meta.card_authors;
const validAuthors = (authors) => Array.isArray(authors) && authors.length > 0 && authors.every((a) => typeof a === 'string' && a.trim());
if (!validAuthors(defaultAuthors)) fail('config.meta.card_authors must list the default card contributors');

// the modules, one folder per historical person
const moduleNames = exists('people') ? fs.readdirSync(path.join(CARDS, 'people'), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort() : [];
// The card of a module is people/<person>/person.yaml. It is the article of the person, and it may carry the other cards of that person inside it, each kind in its own section:
// events, wiki (places, events, model_events, refs), antiques, quotes, and era_text with the text of the era in every language. A card may also stay a file of its own in the folder of its kind.
const moduleCard = Object.fromEntries(moduleNames.map((m) => [m, exists(`people/${m}/person.yaml`) ? read(`people/${m}/person.yaml`) : null]));
const SECTIONS = ['events', 'wiki', 'antiques', 'quotes', 'era_text', 'hook', 'facts', 'dialogue', 'bystanders', 'images', 'self_check', 'pack'];
function embedded(m, dir) {
  const pc = moduleCard[m];
  if (!isObj(pc)) return {};
  const sec = dir.startsWith('wiki/') ? (isObj(pc.wiki) ? pc.wiki[dir.slice(5)] : null) : pc[dir];
  return isObj(sec) ? sec : {};
}
// the article of the person: the card without the sections, and with the ids of its events as a list
function personArticle(m) {
  const pc = moduleCard[m];
  const out = {};
  for (const [k, v] of Object.entries(pc)) {
    if (k === 'events') out.events = isObj(v) ? Object.keys(v) : v;
    else if (!SECTIONS.includes(k)) out[k] = v;
  }
  return out;
}
// the cards of one kind: those in the folder of that kind, those in the same folder inside a module, and those inside the card of a module. A module whose card has no text is not an article.
function entries(dir) {
  const out = yamlFiles(dir).map((f) => ({ id: f.replace(/\.yaml$/, ''), rel: `${dir}/${f}` }));
  for (const m of moduleNames) {
    const authors = moduleCard[m]?.authors;
    if (dir === 'wiki/people') { if (isObj(moduleCard[m]) && moduleCard[m].text !== undefined) out.push({ id: m, rel: `people/${m}/person.yaml`, card: personArticle(m), authors }); continue; }
    for (const f of yamlFiles(`people/${m}/${dir}`)) out.push({ id: f.replace(/\.yaml$/, ''), rel: `people/${m}/${dir}/${f}`, authors });
    for (const [id, card] of Object.entries(embedded(m, dir))) out.push({ id, rel: `people/${m}/person.yaml ${dir} ${id}`, card, authors });
  }
  const seen = new Set();
  for (const e of out) { if (seen.has(e.id)) fail(`${dir}: the id ${e.id} is used twice, see ${e.rel}`); seen.add(e.id); }
  return out;
}
// cards of a kind, ordered by their order field, then by id
function cards(dir) {
  const list = entries(dir).map(({ id, rel, card, authors }) => {
    const c = card ?? read(rel);
    if (!isObj(c)) { fail(`${rel}: a card must be a mapping`); return null; }
    if (c.id !== undefined && c.id !== id) fail(`${rel}: id ${c.id} does not match the file name`);
    if (typeof c.order !== 'number') fail(`${rel}: missing a numeric order`);
    if (c.text !== undefined) for (const l of Object.keys(c.text)) if (!LANGS.includes(l)) fail(`${rel}: text language ${l} is not in config.i18n.locales`);
    if (c.text === undefined || !(config.i18n.fallback in c.text)) fail(`${rel}: the ${config.i18n.fallback} text is missing`);
    const credited = c.authors ?? authors ?? defaultAuthors;
    if (!validAuthors(credited)) fail(`${rel}: authors must list one or more credited contributors`);
    return { id, ...c, authors: credited };
  }).filter(Boolean);
  return list.sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
}
// the structure of a card without its bookkeeping
const struct = (c) => { const { id, order, text, ...rest } = c; return rest; };

const outputs = new Map();
const emitYaml = (rel, obj) => outputs.set(rel, HEADER + yaml.dump(obj, { lineWidth: -1, noRefs: true }));
const emitCopy = (rel, fromRel) => outputs.set(rel, fs.readFileSync(path.join(CARDS, fromRel), 'utf8'));
// a picture is copied byte for byte
const emitBinary = (rel, fromRel) => outputs.set(rel, fs.readFileSync(path.join(CARDS, fromRel)));

// ---------- shared small files ----------
emitYaml('config.yaml', config);
emitYaml('map.yaml', read('config/map.yaml'));
emitYaml('shops.yaml', read('config/shops.yaml'));
// The playlist is whatever midi files are in the music folder, so adding a piece means dropping the file in and building.
const audioCfg = read('config/audio.yaml');
const musicDir = path.join(root, audioCfg.music.folder);
const musicFiles = fs.existsSync(musicDir) ? fs.readdirSync(musicDir).filter((f) => /.midi?$/i.test(f)).sort() : [];
if (!musicFiles.length) fail('no midi files in ' + audioCfg.music.folder);
const nameOf = (f) => { const w = f.replace(/.midi?$/i, '').split('_'); const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1); return { composer: cap(w[0]), title: cap(w.slice(1).join(' ') || w[0]) }; };
for (const f of Object.keys(audioCfg.music.names || {})) if (!musicFiles.includes(f)) fail('audio.yaml names a music file that is not in the folder: ' + f);
audioCfg.music.tracks = musicFiles.map((file) => ({ file, ...(audioCfg.music.names?.[file] || nameOf(file)) }));
delete audioCfg.music.names;
emitYaml('audio.yaml', audioCfg);
emitYaml('hiring.yaml', read('config/hiring.yaml'));
emitYaml('share_qr.yaml', read('config/share_qr.yaml'));
emitCopy('world_land.json', 'world/world_land.json');
// the traveller core: the flat model and the bridge description exported from the LM game bridge, copied as they are
emitCopy('core/traveler_stay.lm.json', 'core/traveler_stay.lm.json');
emitCopy('core/traveler_stay.bridge.json', 'core/traveler_stay.bridge.json');

// ---------- items, antiques ----------
const itemCards = cards('items');
emitYaml('items.yaml', Object.fromEntries(itemCards.map((c) => [c.id, struct(c)])));
const antiqueCards = cards('antiques');
emitYaml('antiques.yaml', { antiques: Object.fromEntries(antiqueCards.map((c) => [c.id, struct(c)])) });

// ---------- staff and traits ----------
const staffRules = read('config/staff_rules.yaml');
const traitCards = cards('traits');
const staffCards = cards('staff');
const quoteCards = cards('quotes');
emitYaml('staff.yaml', {
  attributes: staffRules.attributes, stats: staffRules.stats, derive: staffRules.derive, default_base: staffRules.default_base, default_habit: staffRules.default_habit, gender_class: staffRules.gender_class,
  traits: Object.fromEntries(traitCards.map((c) => [c.id, struct(c)])),
  staff: Object.fromEntries(staffCards.map((c) => [c.id, struct(c)])),
});

// ---------- mainline ----------
const stageCards = cards('mainline');
emitYaml('mainline.yaml', { stages: stageCards.map((c) => ({ id: c.id, ...struct(c) })) });

// ---------- catalogue ----------
const catalogRules = read('config/catalog_rules.yaml');
const eventCards = cards('events');
emitYaml('catalog.yaml', { ...catalogRules, events: eventCards.map((c) => ({ id: c.id, ...struct(c) })) });

// ---------- eras: the model is copied as it is ----------
// an era is a folder with its model and its text, either in cards/eras or in the era folder of a module. The id of an era is the name in its model.
const eraDir = {};
const eraModule = {};
if (exists('eras')) for (const d of fs.readdirSync(path.join(CARDS, 'eras')).sort()) eraDir[d] = `eras/${d}`;
for (const m of moduleNames) {
  if (!exists(`people/${m}/era/model.lm.yaml`)) continue;
  const id = read(`people/${m}/era/model.lm.yaml`).metadata.name;
  if (id in eraDir) fail(`the era ${id} is in two places, ${eraDir[id]} and people/${m}/era`);
  eraDir[id] = `people/${m}/era`;
  eraModule[id] = m;
}
for (const id of config.eras) {
  if (!(id in eraDir)) { fail(`config.eras lists ${id} but no folder holds its model`); continue; }
  emitCopy(`eras/${id}.lm.yaml`, `${eraDir[id]}/model.lm.yaml`);
}
for (const id of Object.keys(eraDir)) if (!config.eras.includes(id)) fail(`${eraDir[id]} is not in config.eras`);

// ---------- encyclopedia ----------
const sectionNames = ['places', 'people', 'events'];
const refCards = cards('wiki/refs');
const modelEventCards = cards('wiki/model_events');
const statCards = cards('wiki/stats');
const sectionCards = Object.fromEntries(sectionNames.map((s) => [s, cards(`wiki/${s}`)]));
// The pictures of a person lie in people/<person>/images, named <kind>.<two digits>.<ext>, and each one is entered in the images section of the card with where it comes from and why it may be used.
// A picture that is not entered, an entry without its picture, or an entry that lacks a field stops the build. The pictures are copied to data/people/<person>/images.
const IMG = config.release.images;
const personImages = {};
for (const m of moduleNames) {
  const dir = `people/${m}/images`;
  const files = exists(dir) ? fs.readdirSync(path.join(CARDS, dir)).sort() : [];
  const entered = isObj(moduleCard[m]) && isObj(moduleCard[m].images) ? moduleCard[m].images : {};
  for (const f of files) {
    const mt = /^([a-z]+)\.(\d{2})\.([a-z0-9]+)$/.exec(f);
    if (!mt || !IMG.kinds.includes(mt[1]) || !IMG.extensions.includes(mt[3])) fail(`${dir}/${f}: a picture is named <kind>.<two digits>.<ext>, the kinds are ${IMG.kinds.join(', ')} and the extensions ${IMG.extensions.join(', ')}`);
    if (!(f in entered)) fail(`${dir}/${f} is not entered in the images of people/${m}/person.yaml`);
  }
  for (const [f, e] of Object.entries(entered)) {
    if (!files.includes(f)) { fail(`people/${m}/person.yaml enters the picture ${f}, which is not in ${dir}`); continue; }
    if (!isObj(e)) { fail(`people/${m}/person.yaml: the entry of ${f} must be a mapping`); continue; }
    for (const k of IMG.fields) if (e[k] === undefined || e[k] === null || String(e[k]).trim() === '') fail(`people/${m}/person.yaml: the picture ${f} has no ${k}`);
    if (!isObj(e.title) || !(config.i18n.fallback in e.title)) fail(`people/${m}/person.yaml: the picture ${f} needs a title in ${config.i18n.fallback}`);
    emitBinary(`people/${m}/images/${f}`, `${dir}/${f}`);
    (personImages[m] = personImages[m] || []).push({ file: f, kind: f.split('.')[0], title: e.title, credit: e.credit, license: e.license, source: e.source });
  }
}
emitYaml('encyclopedia.yaml', {
  refs: Object.fromEntries(refCards.map((c) => [c.id, struct(c)])),
  sections: Object.fromEntries(sectionNames.map((s) => [s, sectionCards[s].map((c) => ({ id: c.id, ...struct(c) }))])),
  model_events: Object.fromEntries(modelEventCards.map((c) => [c.id, struct(c)])),
  stats: statCards.map((c) => ({ id: c.id, ...struct(c) })),
  ...(Object.keys(personImages).length ? { images: personImages } : {}),
});

// ---------- text, one file per language ----------
for (const lang of LANGS) {
  const text = {};
  const partialDir = `text/${lang}`;
  for (const f of yamlFiles(partialDir)) Object.assign(text, merge(text, read(`${partialDir}/${f}`)));
  const put = (section, list, pick) => {
    for (const c of list) {
      const t = c.text && c.text[lang];
      if (t === undefined) continue;
      (text[section] = text[section] || {})[c.id] = pick(t, c);
    }
  };
  put('items', itemCards, (t) => t);
  put('antiques', antiqueCards, (t) => t);
  put('staff', staffCards, (t) => t);
  put('traits', traitCards, (t) => t.name);
  put('trait_notes', traitCards, (t) => ({ pro: t.pro, con: t.con }));
  put('mainline', stageCards, (t) => t);
  put('quotes', quoteCards, (t, c) => ({ ...t, authors: c.authors }));
  put('catalog', eventCards, (t) => t);
  for (const id of config.eras) {
    const rel = `${eraDir[id]}/text.${lang}.yaml`;
    const inCard = eraModule[id] && isObj(moduleCard[eraModule[id]].era_text) ? moduleCard[eraModule[id]].era_text[lang] : undefined;
    if (inCard !== undefined) (text.eras = text.eras || {})[id] = inCard;
    else if (exists(rel)) (text.eras = text.eras || {})[id] = read(rel);
  }
  if (Object.keys(text).length) emitYaml(`i18n/text.${lang}.yaml`, text);

  const enc = {};
  const putEnc = (key, list, pick) => {
    for (const c of list) {
      const t = c.text && c.text[lang];
      if (t === undefined) continue;
      (enc[key] = enc[key] || {})[c.id] = pick(t);
    }
  };
  putEnc('refs', refCards, (t) => t);
  for (const s of sectionNames) {
    for (const c of sectionCards[s]) {
      const t = c.text && c.text[lang];
      if (t === undefined) continue;
      ((enc.sections = enc.sections || {})[s] = enc.sections[s] || {})[c.id] = t;
    }
  }
  putEnc('model_events', modelEventCards, (t) => t);
  putEnc('stats', statCards, (t) => t);
  if (Object.keys(enc).length) emitYaml(`i18n/encyclopedia.${lang}.yaml`, enc);
}

// ---------- the modules are checked as modules ----------
// A folder in people/ is the whole of a person. Its person card must exist, the events it holds must be listed in that card, and an event must not be claimed by two people.
{
  const claimed = new Map();
  for (const m of moduleNames) {
    if (!exists(`people/${m}/person.yaml`)) { fail(`people/${m} has no person.yaml`); continue; }
    const pc = moduleCard[m];
    if (!isObj(pc)) { fail(`people/${m}/person.yaml must be a mapping`); continue; }
    const inCard = embedded(m, 'events');
    const files = yamlFiles(`people/${m}/events`).map((f) => f.replace(/\.yaml$/, ''));
    const held = [...Object.keys(inCard), ...files];
    const listed = Array.isArray(pc.events) ? pc.events : Object.keys(inCard);
    const cardOf = (e) => inCard[e] ?? read(`people/${m}/events/${e}.yaml`);
    for (const e of held) if (!listed.includes(e)) fail(`the event ${e} of people/${m} is not listed in the events of its person.yaml`);
    for (const e of listed) if (!held.includes(e)) fail(`people/${m}/person.yaml lists the event ${e}, which the module does not hold`);
    for (const e of held) { const a = cardOf(e).after; if (a && !held.includes(a)) fail(`the event ${e} of people/${m} opens after ${a}, which is not an event of the same person`); }
    for (const e of held) { if (claimed.has(e)) fail(`the event ${e} is in people/${m} and in people/${claimed.get(e)}`); claimed.set(e, m); }
    for (const k of Object.keys(pc)) if (!['order', 'id', 'text', 'tags', 'related', 'unlock', 'refs', ...SECTIONS].includes(k)) fail(`people/${m}/person.yaml has the key ${k}, which a person card does not use`);
    const stray = fs.readdirSync(path.join(CARDS, 'people', m)).filter((x) => !['person.yaml', 'events', 'era', 'wiki', 'antiques', 'images'].includes(x));
    if (stray.length) fail(`people/${m} holds ${stray.join(', ')}, which a module does not use`);
  }
}

// ---------- the stories are checked against the story standard ----------
// A person card with a fact sheet is a story made by the new process, and it must meet the rules of tools/story_rules.mjs. The published models that have no fact sheet yet are listed.
let storyLine = '';
{
  const refIds = new Set(refCards.map((c) => c.id));
  const traitIds = new Set(traitCards.map((c) => c.id));
  for (const ev of eventCards) {
    for (const ref of ev.refs || []) if (!refIds.has(ref)) fail(`event ${ev.id} names unknown source ${ref}`);
    const variants = ev.scene?.vignettes;
    if (variants === undefined) continue;
    if (!Array.isArray(variants) || !variants.length) {
      fail(`event ${ev.id} needs a non-empty list of vignettes`);
      continue;
    }
    const ids = new Set();
    for (const [i, v] of variants.entries()) {
      if (!isObj(v) || typeof v.id !== 'string' || !v.id || ids.has(v.id)) {
        fail(`event ${ev.id} has an invalid or duplicate vignette id`);
        continue;
      }
      ids.add(v.id);
      if (i === variants.length - 1 ? v.traits !== undefined : !Array.isArray(v.traits) || !v.traits.length || v.traits.some((t) => !traitIds.has(t))) {
        fail(`event ${ev.id} vignette ${v.id} needs known traits, or must be the final unconditional vignette`);
      }
      for (const lang of LANGS) {
        const line = ev.text[lang]?.vignettes?.[v.id];
        if (typeof line !== 'string' || !line.trim()) fail(`event ${ev.id} vignette ${v.id} is missing ${lang} text`);
      }
    }
  }
  const modelOf = (era) => (era && eraDir[era] ? read(`${eraDir[era]}/model.lm.yaml`) : null);
  const people = [];
  for (const m of moduleNames) {
    const pc = moduleCard[m];
    if (!isObj(pc)) continue;
    const evs = embedded(m, 'events');
    const eraOfEvent = (eid) => (evs[eid] ? modelOf(evs[eid].era) : null);
    const own = Object.keys(eraDir).filter((id) => eraModule[id] === m);
    const published = own.some((id) => modelOf(id).metadata.status !== 'draft');
    people.push({ id: m, hasFacts: isObj(pc.facts), published });
    if (!isObj(pc.facts)) continue;
    checkStory(pc, {
      id: m, langs: LANGS, fallback: config.i18n.fallback, hookMax: config.release.hook_max, refIds,
      eraOf: eraOfEvent,
      eraText: (eid, lang) => (isObj(pc.era_text) ? pc.era_text[lang] : (exists(`people/${m}/era/text.${lang}.yaml`) ? read(`people/${m}/era/text.${lang}.yaml`) : null)),
    }, fail);
  }
  const r = storyReport(people);
  storyLine = `stories with a fact sheet: ${r.done.join(', ') || 'none'}; published models without one: ${r.missing.join(', ') || 'none'}`;
}

// ---------- write or check ----------
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
const generated = new Set(outputs.keys());
let differs = 0;
for (const [rel, content] of outputs) {
  const file = path.join(OUT, rel);
  const binary = Buffer.isBuffer(content);
  const current = fs.existsSync(file) ? fs.readFileSync(file, binary ? undefined : 'utf8') : null;
  if (binary ? (current !== null && current.equals(content)) : current === content) continue;
  differs++;
  if (check) { console.log('differs: data/' + rel); continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log('wrote data/' + rel);
}
// files in data/ that no card produces are stale
const walk = (dir, base = '') => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name), base + e.name + '/') : [base + e.name]));
for (const rel of walk(OUT)) {
  if (generated.has(rel)) continue;
  differs++;
  if (check) console.log('stale: data/' + rel); else { fs.unlinkSync(path.join(OUT, rel)); console.log('removed data/' + rel); }
}
console.log(`${outputs.size} files from ${entries('items').length + entries('events').length + entries('staff').length + entries('traits').length} item, event, staff and trait cards and more, ${moduleNames.length} person modules`);
if (check && differs) { console.log(`${differs} files differ, run node tools/build_data.mjs`); process.exit(1); }
console.log(storyLine);
if (check) console.log('data is up to date');
