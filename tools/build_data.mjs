// ---------- the modules are checked as modules ----------
// A folder in people/ is the whole of a person. Its person card must exist, the events it holds must be listed in that card, and an event must not be claimed by two people.
{
  const claimed = new Map();
  for (const m of moduleNames) {
    if (!exists(`people/${m}/person.yaml`)) { fail(`people/${m} has no person.yaml`); continue; }
    const pc = moduleCard[m];
    if (!isObj(pc)) { fail(`people/${m}/person.yaml must be a mapping`); continue; }
    const inCard = embedded(m, 'events');
    const files = yamlFiles(`people/${m}/events`).map((f) => f.replace(/\.yaml$/, ''));
    const held = [...Object.keys(inCard), ...files];
    const listed = Array.isArray(pc.events) ? pc.events : Object.keys(inCard);
    const cardOf = (e) => inCard[e] ?? read(`people/${m}/events/${e}.yaml`);
    for (const e of held) if (!listed.includes(e)) fail(`the event ${e} of people/${m} is not listed in the events of its person.yaml`);
    for (const e of listed) if (!held.includes(e)) fail(`people/${m}/person.yaml lists the event ${e}, which the module does not hold`);
    // the events of a person stand side by side: none waits for another to be visited
    for (const e of held) if (cardOf(e).after !== undefined) fail(`the event ${e} of people/${m} has after, but the events of a person are not opened one after another`);
    for (const e of held) { if (claimed.has(e)) fail(`the event ${e} is in people/${m} and in people/${claimed.get(e)}`); claimed.set(e, m); }
    for (const k of Object.keys(pc)) if (!['order', 'id', 'text', 'tags', 'related', 'unlock', 'refs', ...SECTIONS].includes(k)) fail(`people/${m}/person.yaml has the key ${k}, which a person card does not use`);
    const stray = fs.readdirSync(path.join(CARDS, 'people', m)).filter((x) => !['person.yaml', 'events', 'era', 'wiki', 'antiques', 'images'].includes(x));
    if (stray.length) fail(`people/${m} holds ${stray.join(', ')}, which a module does not use`);
  }
}

// ---------- the stories are checked against the story standard ----------
// A person card with a fact sheet is a story made by the new process, and it must meet the rules of tools/story_rules.mjs. The published models that have no fact sheet yet are listed.
let storyLine = '';
{
  const refIds = new Set(refCards.map((c) => c.id));
  const echoRefIds = new Set(refCards.filter((card) => card.status === 'checked').map((card) => card.id));
  const traitIds = new Set(traitCards.map((c) => c.id));
  // a vignette is chosen by the traits of the traveller and, in a scene story, by the star points won or missed on the trip, see vignetteFor in js/backend.js
  function checkVignettes(id, variants, localText, pointIds = null) {
    if (variants === undefined) return;
    if (!Array.isArray(variants) || !variants.length) {
      fail(`${id} needs a non-empty list of vignettes`);
      return;
    }
    const ids = new Set();
    for (const [i, v] of variants.entries()) {
      if (!isObj(v) || typeof v.id !== 'string' || !v.id || ids.has(v.id)) {
        fail(`${id} has an invalid or duplicate vignette id`);
        continue;
      }
      ids.add(v.id);
      const conds = ['won', 'missed'].filter((k) => v[k] !== undefined);
      for (const k of conds) {
        if (!pointIds) fail(`${id} vignette ${v.id} names star points by ${k}, which only a scene story has`);
        else if (!Array.isArray(v[k]) || !v[k].length || v[k].some((p) => !pointIds.has(p))) fail(`${id} vignette ${v.id} needs known star points in ${k}`);
      }
      if (v.traits !== undefined && (!Array.isArray(v.traits) || !v.traits.length || v.traits.some((t) => !traitIds.has(t)))) fail(`${id} vignette ${v.id} needs known traits`);
      const conditional = v.traits !== undefined || conds.length > 0;
      if (i === variants.length - 1 ? conditional : !conditional) {
        fail(`${id} vignette ${v.id}: every vignette but the last needs traits or star points, and the last has none`);
      }
      for (const lang of STORY_LANGS) {
        const line = localText(lang)?.vignettes?.[v.id];
        if (typeof line !== 'string' || !line.trim()) fail(`${id} vignette ${v.id} is missing ${lang} text`);
      }
    }
  }
  for (const ev of eventCards) {
    for (const ref of ev.refs || []) if (!refIds.has(ref)) fail(`event ${ev.id} names unknown source ${ref}`);
    checkVignettes(`event ${ev.id}`, ev.scene?.vignettes, (lang) => ev.text[lang], new Set((ev.scene?.points ?? []).map((p) => p.id)));
    // story prose, cards/README.md: complete when present, so no won point or ending falls back to the plain line in the middle of the prose
    const points = ev.scene?.points ?? [];
    const pointIds = new Set(points.map((point) => point.id));
    const paragraph = (value) => typeof value === 'string' && !!value.trim() && !value.includes('\n');
    // a paragraph of a point is one string, or a mapping keyed by tags joined by + with an `else`, read for the employee like the remarks
    const variants = (value) => (paragraph(value) ? [value] : isObj(value) && 'else' in value && Object.values(value).every(paragraph) ? Object.values(value) : null);
    // the shape compared across languages: the fields in any order, the keys within a field in their order, since the order of outcomes and excerpts is their priority
    const shape = (prose) => JSON.stringify(Object.fromEntries(Object.entries(prose).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => [k, isObj(v) ? Object.fromEntries(Object.entries(v).map(([id, x]) => [id, isObj(x) ? Object.keys(x) : 1])) : Array.isArray(v) ? v.length : 1])));
    const shapes = {};
    // the text of the story in every language that carries it: the person card, and over it nothing, else the language's own catalogue file
    const texts = Object.fromEntries(LANGS.map((lang) => [lang, ev.text[lang] ?? langCatalog[lang][ev.id]]).filter(([, t]) => t !== undefined));
    for (const [lang, text] of Object.entries(texts)) {
      const prose = text.story_prose;
      if (prose === undefined) continue;
      const where = ev.id + ' ' + lang + ' story_prose';
      if (!isObj(prose)) {
        fail(where + ' must be a mapping');
        continue;
      }
      for (const key of Object.keys(prose)) if (!['opening', 'points', 'outcomes', 'none', 'desync', 'not_admitted', 'excerpts'].includes(key)) fail(where + ' has an unknown field ' + key);
      if (!Array.isArray(prose.opening) || !prose.opening.length || !prose.opening.every(paragraph)) fail(where + '.opening must contain nonempty paragraphs');
      const endings = ['none', 'not_admitted', ...(points.some((p) => p.guard) ? ['desync'] : [])];
      for (const key of endings) if (!paragraph(prose[key])) fail(where + '.' + key + ' must be one paragraph');
      if (prose.desync !== undefined && !endings.includes('desync')) fail(where + '.desync is never read: the scene has no guard point');
      for (const key of ['points', 'outcomes', 'excerpts']) {
        if (!isObj(prose[key])) {
          fail(where + '.' + key + ' must be a mapping keyed by point ID');
          continue;
        }
        for (const [id, value] of Object.entries(prose[key])) {
          if (!(pointIds.has(id) || (key === 'outcomes' && id === 'all'))) fail(where + '.' + key + '.' + id + ' is not a point of the scene');
          else if (key === 'points' ? !variants(value) : !paragraph(value)) fail(where + '.' + key + '.' + id + (key === 'points' ? ' needs a paragraph, or paragraphs keyed by tags with an else' : ' needs a paragraph'));
          else if (key === 'excerpts' && !(variants(prose.points?.[id]) ?? []).every((x) => x.includes(value))) fail(where + '.excerpts.' + id + ' must quote every paragraph of its point');
        }
      }
      if (isObj(prose.points)) for (const id of pointIds) if (!(id in prose.points)) fail(where + '.points.' + id + ' is missing: every point of the scene needs its paragraph');
      if (isObj(prose.outcomes) && !Object.keys(prose.outcomes).some((id) => id !== 'all')) fail(where + '.outcomes needs a paragraph for at least one point');
      shapes[lang] = shape(prose);
    }
    // Chinese is written first and is the master; English and the other languages follow once the Chinese is approved. A language that has not
    // been written leaves the block out and tells the trip in plain lines; one that has must match the Chinese field for field and key for key.
    if (Object.keys(shapes).length) {
      if (!shapes.zh) fail(ev.id + ' story_prose is written in ' + Object.keys(shapes).join(', ') + ' but not in zh, which is written first');
      else for (const [lang, sh] of Object.entries(shapes)) if (sh !== shapes.zh) fail(ev.id + ' ' + lang + ' story_prose does not have the same fields and keys as zh');
      // a story is written whole: once the Chinese prose is there, English, the fallback, and every language that carries the card have theirs,
      // so no language shows the plain lines for one story while it reads the prose for another
      if (shapes.zh) for (const lang of LANGS) if (!shapes[lang] && (lang === config.i18n.fallback || texts[lang])) fail(ev.id + ' story_prose is written in zh but not in ' + lang + (lang === config.i18n.fallback ? ', the fallback' : ', which carries the card') + (config.i18n.convert?.[lang] ? '; run python tools/story_prose_convert.py ' + ev.id : ''));
    }
  }
  const modelOf = (era) => (era && eraDir[era] ? (eraModel[era] ?? modelOfDir(eraDir[era])).raw : null);
  const modelText = (id, lang) => moduleCard[eraModule[id]]?.era_text?.[lang] ?? (exists(`${eraDir[id]}/text.${lang}.yaml`) ? read(`${eraDir[id]}/text.${lang}.yaml`) : null);
  const eventSources = new Set(sectionCards.events.map((c) => c.id));
  for (const id of config.eras) {
    const meta = modelOf(id).metadata;
    if (meta.vignettes !== undefined && !eventSources.has(meta.vignette_source)) fail(`model ${id} needs a wiki event as its vignette source`);
    checkVignettes(`model ${id}`, meta.vignettes, (lang) => modelText(id, lang));
  }
  const people = [];
  const reviewByPerson = new Map();
  for (const m of moduleNames) {
    const pc = moduleCard[m];
    if (!isObj(pc)) continue;
    const evs = embedded(m, 'events');
    const eraOfEvent = (eid) => (evs[eid] ? modelOf(evs[eid].era) : null);
    const own = Object.keys(eraDir).filter((id) => eraModule[id] === m);
    const published = own.some((id) => modelOf(id).metadata.status !== 'draft');
    // the echoes of the person: every quote with a tier is checked, and a published story with a fact sheet should have the two tiers 5.15 asks for
    const tiersHeld = checkEchoes(pc.quotes, { id: m, langs: STORY_LANGS, tiers: config.echo.tiers, refIds: echoRefIds }, fail);
    people.push({ id: m, hasFacts: isObj(pc.facts), published });
    reviewByPerson.set(m, { card: pc, tiers: tiersHeld });
    if (!isObj(pc.facts)) continue;
    checkStory(pc, {
      id: m, langs: STORY_LANGS, fallback: config.i18n.fallback, hookMax: config.release.hook_max, refIds,
      eraOf: eraOfEvent,
      eraText: (eid, lang) => (isObj(pc.era_text) ? pc.era_text[lang] : (exists(`people/${m}/era/text.${lang}.yaml`) ? read(`people/${m}/era/text.${lang}.yaml`) : null)),
    }, fail);
  }
  const r = storyReport(people);
  storyLine = `stories with a fact sheet: ${r.done.join(', ') || 'none'}; published models without one: ${r.missing.join(', ') || 'none'}`;
  const ownerByEvent = new Map(sectionCards.people.flatMap((person) => (person.events || []).map((id) => [id, person.id])));
  const personIds = new Set(sectionCards.people.map((person) => person.id));
  const open = eventCards.filter((event) => !event.draft && !event.deprecated && (!config.release.ready_only || event.ready));
  const rows = open.map((event) => {
    const owner = ownerByEvent.get(event.id);
    const review = reviewByPerson.get(owner);
    const rawModel = modelOf(event.era);
    const modeledDates = Object.values(rawModel?.metadata.status !== 'draft' ? rawModel?.milestones || {} : {}).filter((milestone) =>
      milestone.tag === 'history' && milestone.needs_traveler === false && milestone.date && review?.card.facts?.[milestone.fact]);
    const timeline = Object.values(review?.card.facts || {}).filter((fact) =>
      fact.checked !== 'single' && fact.level !== 'unused' &&
      fact.use?.some((use) => use === 'history' || use === 'story') &&
      STORY_LANGS.every((lang) => fact.line?.[lang]));
    const missingTiers = ['full', 'none'].filter((tier) => !review?.tiers.has(tier));
    const local = event.text[config.i18n.fallback];
    const unlinkedPeople = [...new Set([...Object.values(local.shift || {}), local.shift_all].filter((shift) => shift?.who && !personIds.has(shift.who)).map((shift) => shift.who))];
    const gaps = [];
    if (!owner) gaps.push('no person article');
    if (!review?.card.facts) gaps.push('no fact sheet');
    if (Math.max(timeline.length, modeledDates.length) < 2) gaps.push('fewer than two documented history beats');
    if (Object.keys(review?.card.bystanders || {}).length < 2) gaps.push('fewer than two bystanders');
    if (unlinkedPeople.length) gaps.push('branch figures without an article: ' + unlinkedPeople.join(', '));
    if (missingTiers.length) gaps.push('missing echo ' + missingTiers.join('/'));
    return { event: event.id, owner, gaps, missingTiers };
  });
  const noEcho = rows.filter((row) => row.missingTiers.length);
  storyLine += `
open stories without the echoes full and none: ${noEcho.length}/${open.length}${noEcho.length ? ', the first ' + noEcho.slice(0, 8).map((row) => row.event).join(', ') : ''}`;
  // every open story with a scene is told by its Chinese story prose; the list is the work left, and the story agent takes its batches from it
  const noProse = open.filter((event) => event.scene && !event.text?.zh?.story_prose).map((event) => event.id);
  storyLine += `
open stories without Chinese story prose: ${noProse.length}/${open.filter((event) => event.scene).length}${noProse.length ? ': ' + noProse.join(', ') : ''}`;
  if (storyDetails) storyLine += '\n' + rows.map(({ event, owner, gaps }) =>
    `  ${event} (${owner || 'unlinked'}): ${gaps.length ? gaps.join('; ') : 'structural checks clear; editorial review still required'}`).join('\n');
}

