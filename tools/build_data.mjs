// Packs the cards folder into the data the game reads. Edit the cards, then run:
//   node tools/build_data.mjs           write data/
//   node tools/build_data.mjs --check   write nothing, exit 1 if data/ differs from what the cards would produce
// One card is one yaml file. A card holds the structure of a thing and its text in every language, so one thing is changed in one place.
// See cards/README.md for the layout.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const yaml = createRequire(import.meta.url)(path.join(root, 'vendor/js-yaml.min.js'));
const check = process.argv.includes('--check');
const CARDS = path.join(root, 'cards');
const OUT = path.join(root, 'data');
const HEADER = '# Generated by tools/build_data.mjs from the cards folder. Do not edit this file, edit the cards and run the build.\n';

const problems = [];
const fail = (msg) => problems.push(msg);
const isObj = (x) => x !== null && typeof x === 'object' && !Array.isArray(x);
const read = (rel) => yaml.load(fs.readFileSync(path.join(CARDS, rel), 'utf8'));
const exists = (rel) => fs.existsSync(path.join(CARDS, rel));
const yamlFiles = (dir) => (exists(dir) ? fs.readdirSync(path.join(CARDS, dir)).filter((f) => f.endsWith('.yaml')).sort() : []);
// objects merge key by key, anything else is replaced whole, the same rule the game uses for languages
function merge(base, over) {
  if (!isObj(base) || !isObj(over)) return over;
  const out = { ...base };
  for (const k of Object.keys(over)) out[k] = k in base ? merge(base[k], over[k]) : over[k];
  return out;
}

const config = read('config/config.yaml');
const LANGS = Object.keys(config.i18n.locales);

// cards in a folder, ordered by their order field, then by id
function cards(dir) {
  const list = yamlFiles(dir).map((f) => {
    const id = f.replace(/\.yaml$/, '');
    const c = read(`${dir}/${f}`);
    if (!isObj(c)) { fail(`${dir}/${f}: a card must be a mapping`); return null; }
    if (c.id !== undefined && c.id !== id) fail(`${dir}/${f}: id ${c.id} does not match the file name`);
    if (typeof c.order !== 'number') fail(`${dir}/${f}: missing a numeric order`);
    if (c.text !== undefined) for (const l of Object.keys(c.text)) if (!LANGS.includes(l)) fail(`${dir}/${f}: text language ${l} is not in config.i18n.locales`);
    if (c.text === undefined || !(config.i18n.fallback in c.text)) fail(`${dir}/${f}: the ${config.i18n.fallback} text is missing`);
    return { id, ...c };
  }).filter(Boolean);
  return list.sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
}
// the structure of a card without its bookkeeping
const struct = (c) => { const { id, order, text, ...rest } = c; return rest; };

const outputs = new Map();
const emitYaml = (rel, obj) => outputs.set(rel, HEADER + yaml.dump(obj, { lineWidth: -1, noRefs: true }));
const emitCopy = (rel, fromRel) => outputs.set(rel, fs.readFileSync(path.join(CARDS, fromRel), 'utf8'));

// ---------- shared small files ----------
emitYaml('config.yaml', config);
emitYaml('map.yaml', read('config/map.yaml'));
emitYaml('shops.yaml', read('config/shops.yaml'));
// The playlist is whatever midi files are in the music folder, so adding a piece means dropping the file in and building.
const audioCfg = read('config/audio.yaml');
const musicDir = path.join(root, audioCfg.music.folder);
const musicFiles = fs.existsSync(musicDir) ? fs.readdirSync(musicDir).filter((f) => /.midi?$/i.test(f)).sort() : [];
if (!musicFiles.length) fail('no midi files in ' + audioCfg.music.folder);
const nameOf = (f) => { const w = f.replace(/.midi?$/i, '').split('_'); const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1); return { composer: cap(w[0]), title: cap(w.slice(1).join(' ') || w[0]) }; };
for (const f of Object.keys(audioCfg.music.names || {})) if (!musicFiles.includes(f)) fail('audio.yaml names a music file that is not in the folder: ' + f);
audioCfg.music.tracks = musicFiles.map((file) => ({ file, ...(audioCfg.music.names?.[file] || nameOf(file)) }));
delete audioCfg.music.names;
emitYaml('audio.yaml', audioCfg);
emitYaml('hiring.yaml', read('config/hiring.yaml'));
emitYaml('share_qr.yaml', read('config/share_qr.yaml'));
emitCopy('world_land.json', 'world/world_land.json');

// ---------- items, antiques ----------
const itemCards = cards('items');
emitYaml('items.yaml', Object.fromEntries(itemCards.map((c) => [c.id, struct(c)])));
const antiqueCards = cards('antiques');
emitYaml('antiques.yaml', { antiques: Object.fromEntries(antiqueCards.map((c) => [c.id, struct(c)])) });

// ---------- staff and traits ----------
const staffRules = read('config/staff_rules.yaml');
const traitCards = cards('traits');
const staffCards = cards('staff');
const quoteCards = cards('quotes');
emitYaml('staff.yaml', {
  attributes: staffRules.attributes, stats: staffRules.stats, derive: staffRules.derive, default_base: staffRules.default_base, default_habit: staffRules.default_habit,
  traits: Object.fromEntries(traitCards.map((c) => [c.id, struct(c)])),
  staff: Object.fromEntries(staffCards.map((c) => [c.id, struct(c)])),
});

// ---------- mainline ----------
const stageCards = cards('mainline');
emitYaml('mainline.yaml', { stages: stageCards.map((c) => ({ id: c.id, ...struct(c) })) });

// ---------- catalogue ----------
const catalogRules = read('config/catalog_rules.yaml');
const eventCards = cards('events');
emitYaml('catalog.yaml', { ...catalogRules, events: eventCards.map((c) => ({ id: c.id, ...struct(c) })) });

// ---------- eras: the model is copied as it is ----------
const eraDirs = fs.existsSync(path.join(CARDS, 'eras')) ? fs.readdirSync(path.join(CARDS, 'eras')).sort() : [];
for (const id of config.eras) {
  if (!eraDirs.includes(id)) { fail(`config.eras lists ${id} but cards/eras/${id} is missing`); continue; }
  emitCopy(`eras/${id}.lm.yaml`, `eras/${id}/model.lm.yaml`);
}
for (const id of eraDirs) if (!config.eras.includes(id)) fail(`cards/eras/${id} is not in config.eras`);

// ---------- encyclopedia ----------
const sectionNames = ['places', 'people', 'events', 'stories'];
const refCards = cards('wiki/refs');
const modelEventCards = cards('wiki/model_events');
const statCards = cards('wiki/stats');
const sectionCards = Object.fromEntries(sectionNames.map((s) => [s, cards(`wiki/${s}`)]));
emitYaml('encyclopedia.yaml', {
  refs: Object.fromEntries(refCards.map((c) => [c.id, struct(c)])),
  sections: Object.fromEntries(sectionNames.map((s) => [s, sectionCards[s].map((c) => ({ id: c.id, ...struct(c) }))])),
  model_events: Object.fromEntries(modelEventCards.map((c) => [c.id, struct(c)])),
  stats: statCards.map((c) => ({ id: c.id, ...struct(c) })),
});

// ---------- text, one file per language ----------
for (const lang of LANGS) {
  const text = {};
  const partialDir = `text/${lang}`;
  for (const f of yamlFiles(partialDir)) Object.assign(text, merge(text, read(`${partialDir}/${f}`)));
  const put = (section, list, pick) => {
    for (const c of list) {
      const t = c.text && c.text[lang];
      if (t === undefined) continue;
      (text[section] = text[section] || {})[c.id] = pick(t, c);
    }
  };
  put('items', itemCards, (t) => t);
  put('antiques', antiqueCards, (t) => t);
  put('staff', staffCards, (t) => t);
  put('traits', traitCards, (t) => t.name);
  put('trait_notes', traitCards, (t) => ({ pro: t.pro, con: t.con }));
  put('mainline', stageCards, (t) => t);
  put('quotes', quoteCards, (t) => t);
  put('catalog', eventCards, (t) => t);
  for (const id of config.eras) {
    const rel = `eras/${id}/text.${lang}.yaml`;
    if (exists(rel)) (text.eras = text.eras || {})[id] = read(rel);
  }
  if (Object.keys(text).length) emitYaml(`i18n/text.${lang}.yaml`, text);

  const enc = {};
  const putEnc = (key, list, pick) => {
    for (const c of list) {
      const t = c.text && c.text[lang];
      if (t === undefined) continue;
      (enc[key] = enc[key] || {})[c.id] = pick(t);
    }
  };
  putEnc('refs', refCards, (t) => t);
  for (const s of sectionNames) {
    for (const c of sectionCards[s]) {
      const t = c.text && c.text[lang];
      if (t === undefined) continue;
      ((enc.sections = enc.sections || {})[s] = enc.sections[s] || {})[c.id] = t;
    }
  }
  putEnc('model_events', modelEventCards, (t) => t);
  putEnc('stats', statCards, (t) => t);
  if (Object.keys(enc).length) emitYaml(`i18n/encyclopedia.${lang}.yaml`, enc);
}

// ---------- write or check ----------
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
const generated = new Set(outputs.keys());
let differs = 0;
for (const [rel, content] of outputs) {
  const file = path.join(OUT, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) continue;
  differs++;
  if (check) { console.log('differs: data/' + rel); continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log('wrote data/' + rel);
}
// files in data/ that no card produces are stale
const walk = (dir, base = '') => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name), base + e.name + '/') : [base + e.name]));
for (const rel of walk(OUT)) {
  if (generated.has(rel)) continue;
  differs++;
  if (check) console.log('stale: data/' + rel); else { fs.unlinkSync(path.join(OUT, rel)); console.log('removed data/' + rel); }
}
console.log(`${outputs.size} files from ${yamlFiles('items').length + yamlFiles('events').length + yamlFiles('staff').length + yamlFiles('traits').length} item, event, staff and trait cards and more`);
if (check && differs) { console.log(`${differs} files differ, run node tools/build_data.mjs`); process.exit(1); }
if (check) console.log('data is up to date');
